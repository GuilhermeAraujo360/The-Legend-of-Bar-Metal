/* ============================================================
 * terminal_goto
 *
 * Posiciona o cursor do terminal na linha/coluna informada
 * (1-based), via sequência de escape ANSI/VT100: ESC [ row ; col H
 *
 * Linhas vão de 1 a 24 e colunas de 1 a 81, então 2 dígitos
 * decimais bastam pra cada um — não precisa de algo genérico.
 * ============================================================ */
static void terminal_goto(int row, int col)
{
    char buf[12];
    int  i = 0;

    buf[i++] = '\033';
    buf[i++] = '[';

    if (row >= 10) buf[i++] = '0' + (row / 10);
    buf[i++] = '0' + (row % 10);

    buf[i++] = ';';

    if (col >= 10) buf[i++] = '0' + (col / 10);
    buf[i++] = '0' + (col % 10);

    buf[i++] = 'H';
    buf[i]   = '\0';

    print_string(buf);
}

void mapa_print(void)
{
    int i, j;


    print_string("\033[2J\033[H");

    for(i = 0; i < 24; i++)
    {
        for(j = 0; j < 80; j++)
        {
            if(i == jogador.y && j == jogador.x)
                print_char('@');
            else
                print_char(mapa[i][j]);
        }

        print_string("\r\n");
    }
}

void move_player_from_joystick(void)
{
    int nx = jogador.x;
    int ny = jogador.y;

    if(left)  { left  = false; nx--; }
    if(right) { right = false; nx++; }
    if(up)    { up    = false; ny--; }
    if(down)  { down  = false; ny++; }

    left = right = up = down = false;

    if(nx < 0 || nx >= 80 || ny < 0 || ny >= 24)
        return;

    if(mapa[ny][nx] != '#')
    {
        int ox = jogador.x;
        int oy = jogador.y;

        jogador.x = nx;
        jogador.y = ny;

        /* Redesenha só as duas células que mudaram 
         * em vez do mapa inteiro. É bem mais rápido
         * pela UART e fica suave em vez de "desenhar" a
         * tela toda de novo a cada passo. */
        terminal_goto(oy + 1, ox + 1);
        print_char(mapa[oy][ox]);

        terminal_goto(ny + 1, nx + 1);
        print_char('@');
    }
}